package main

import (
	"errors"
	"fmt"
	"strings"
	"unicode/utf16"
)

// generateTS renders the TypeScript module of the emoji pattern
// (ts/src/emoji-regex.gen.ts).
//
// TS版はJavaScriptの正規表現をそのまま使うので、mfm-jsと同じエンジンで同じ
// 選択肢から読む。変換するのは、照合の前に弾くための先頭のコードユニットの
// 一覧だけ。一致は必ずペアになったサロゲートか単独のBMPの文字で始まる
// (pairSurrogatesが確かめる)ので、アストラルの先頭の文字は上位サロゲートに置き換える。
func generateTS(src regexSource) ([]byte, error) {
	alt, err := parseJS(src.source)
	if err != nil {
		return nil, err
	}
	if err := pairSurrogates(alt); err != nil {
		return nil, err
	}
	if minW, _ := alt.width(); minW == 0 {
		return nil, errors.New("the regex can match the empty string")
	}
	if n := alt.countAlternatives(); n < 200 {
		return nil, fmt.Errorf("the regex has only %d alternatives; extraction probably went wrong", n)
	}
	units := firstUnits(alt.firstRunes())

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/emojiregex from @misskey-dev/emoji-data %s; DO NOT EDIT.\n\n", src.version)
	b.WriteString("/** The @misskey-dev/emoji-data version the pattern was generated from. */\n")
	fmt.Fprintf(&b, "export const emojiDataVersion = %s;\n\n", jsQuote(src.version))
	b.WriteString("/** The mfm-js version whose unicodeEmoji the pattern reproduces. */\n")
	fmt.Fprintf(&b, "export const emojiMfmJsVersion = %s;\n\n", jsQuote(src.mfmjs))
	b.WriteString("/**\n")
	b.WriteString(" * The emoji regex of mfm-js, without the `u` flag like mfm-js, made sticky so\n")
	b.WriteString(" * that it matches at `lastIndex` only.\n")
	b.WriteString(" */\n")
	fmt.Fprintf(&b, "export const emojiRegex = new RegExp(%s, 'y');\n\n", jsQuote(src.source))
	b.WriteString("/** The sorted, inclusive [lo, hi] pairs of the UTF-16 code units a match can start with. */\n")
	b.WriteString("export const emojiFirstUnits: readonly number[] = [\n")
	for _, r := range units {
		fmt.Fprintf(&b, "\t0x%04x, 0x%04x,\n", r.lo, r.hi)
	}
	b.WriteString("];\n")
	return []byte(b.String()), nil
}

// firstUnits maps sorted code point ranges to the sorted, merged ranges of
// their first UTF-16 code units.
func firstUnits(rs []charRange) []charRange {
	var out []charRange
	for _, r := range rs {
		if r.lo <= 0xFFFF {
			out = append(out, charRange{r.lo, min(r.hi, 0xFFFF)})
		}
		if r.hi > 0xFFFF {
			lo, _ := utf16.EncodeRune(max(r.lo, 0x10000))
			hi, _ := utf16.EncodeRune(r.hi)
			out = append(out, charRange{lo, hi})
		}
	}
	return mergeRanges(out)
}

// jsQuote returns s as a JavaScript string literal in single quotes, with
// everything outside printable ASCII written as \uXXXX escapes.
func jsQuote(s string) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, u := range utf16.Encode([]rune(s)) {
		switch {
		case u == '\'' || u == '\\':
			b.WriteByte('\\')
			b.WriteByte(byte(u))
		case u >= 0x20 && u < 0x7f:
			b.WriteByte(byte(u))
		default:
			fmt.Fprintf(&b, "\\u%04x", u)
		}
	}
	b.WriteByte('\'')
	return b.String()
}
